import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { transformSync } from 'esbuild';
import { createHash } from 'node:crypto';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const cssDir = path.join(root, 'src/MovasseghiShop.Web/wwwroot/css');
const parts = [
  'site.css',
  'ux-mobile.css',
  'ux-desktop.css',
  'ux-cart.css',
  'ux-product-dual.css',
  'ux-scroll-reveal.css',
];

let out = '';
for (const file of parts) {
  const p = path.join(cssDir, file);
  out += `\n/* === ${file} === */\n`;
  out += fs.readFileSync(p, 'utf8');
  out += '\n';
}

const target = path.join(cssDir, 'storefront.bundle.css');
// Match ASP.NET's asp-append-version hash, so CSS and the font preload reuse
// one request and a replaced font can safely have a year-long cache lifetime.
const fontName = 'Vazirmatn-var.woff2';
const fontVersion = createHash('sha256').update(fs.readFileSync(path.join(cssDir, '..', 'fonts', fontName))).digest('base64url');
out = out.replaceAll(`../fonts/${fontName}`, `../fonts/${fontName}?v=${fontVersion}`);
const { code, warnings } = transformSync(out, { loader: 'css', minify: true });
if (warnings.length) throw new Error(warnings.map(w => w.text).join('\n'));
fs.writeFileSync(target, `/* Generated by npm run build:storefront-css; do not edit. */\n${code}`, 'utf8');
console.log(`Wrote ${target} (${(Buffer.byteLength(code) / 1024).toFixed(1)} KB)`);
