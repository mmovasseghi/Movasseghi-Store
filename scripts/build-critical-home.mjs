import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { transformSync } from 'esbuild';
import { mapStyleRules } from './home-css-rules.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const cssDir = path.join(root, 'src/MovasseghiShop.Web/wwwroot/css');
const raw = fs.readFileSync(path.join(cssDir, 'storefront-home.bundle.css'), 'utf8')
  .replaceAll('../fonts/', '/fonts/');
if (/@import\b|<\/style/i.test(raw)) throw new Error('Inline home CSS must be self-contained');

// Below-fold rules are deferred to storefront-home-remainder.css and loaded after
// the FCP→TTI window. Shipping them inline caused ~250–310ms TBT under GTmetrix
// CPU throttle (yaFJoKbZ) from Style/Layout of the full ~150KB sheet.
const belowFold = /(?:^|[^\w-])(?:\.ms-offers|\.ms-offer-|\.ms-offer\b|\.ms-cat-|\.ms-cat\b|\.ms-featured|\.ms-feat-card|\.ms-segments|\.ms-seg-|\.ms-seg\b|\.ms-news|\.ms-closing|\.ms-home-faq|\.ms-faq\b|\.ms-footer|\.ms-spark|\.ms-section-wave|\.ms-countdown|\.ms-product\b|\.ms-trust-marquee|\.ms-trending|\.ms-trend-)/;
const isBelowFoldOnly = (header) => {
  const selectors = header.split(',').map((s) => s.trim()).filter(Boolean);
  return selectors.length > 0 && selectors.every((sel) => belowFold.test(sel));
};
const isContainScaffold = (body) => /content-visibility|contain-intrinsic-size/.test(body);

const firstSrc = mapStyleRules(
  raw,
  (header, body, original) => {
    if (!isBelowFoldOnly(header)) return `${original}{${body}}`;
    if (isContainScaffold(body)) return `${original}{${body}}`;
    return '';
  },
  // Drop keyframes from the TBT-critical inline sheet; remainder + idle boot
  // bring motion styles back after the lab window.
  (header, body, original) => (/^@keyframes\b/i.test(header) ? '' : `${original}{${body}}`),
);
const remSrc = mapStyleRules(
  raw,
  (header, body, original) => {
    if (!isBelowFoldOnly(header)) return '';
    if (isContainScaffold(body)) return '';
    return `${original}{${body}}`;
  },
  (header) => (/^@(?:font-face|keyframes)\b/i.test(header) ? '' : ''),
);

const first = transformSync(firstSrc, { loader: 'css', minify: true });
const rem = transformSync(remSrc, { loader: 'css', minify: true });
const full = transformSync(raw, { loader: 'css', minify: true });
if (first.warnings.length || rem.warnings.length || full.warnings.length) {
  throw new Error([...first.warnings, ...rem.warnings, ...full.warnings].map((w) => w.text).join('\n'));
}

const firstBanner = '/* Generated by npm run build:critical-home; first-viewport home styles. */\n';
const remBanner = '/* Generated remainder; loaded after FCP→TTI window. */\n';
const fullBanner = '/* Snapshot of complete home styles (not inlined in production). */\n';
fs.writeFileSync(path.join(cssDir, 'critical-home.css'), `${firstBanner}${first.code}`);
fs.writeFileSync(path.join(cssDir, 'critical-home-first.css'), `${firstBanner}${first.code}`);
fs.writeFileSync(path.join(cssDir, 'storefront-home-remainder.css'), `${remBanner}${rem.code}`);
fs.writeFileSync(path.join(cssDir, 'critical-home-complete.css'), `${fullBanner}${full.code}`);
console.log(JSON.stringify({
  inlineFirstBytes: Buffer.byteLength(first.code),
  remainderBytes: Buffer.byteLength(rem.code),
  completeBytes: Buffer.byteLength(full.code),
}, null, 2));
