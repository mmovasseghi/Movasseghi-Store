import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { transformSync } from 'esbuild';
import { mapStyleRules } from './home-css-rules.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const cssDir = path.join(root, 'src/MovasseghiShop.Web/wwwroot/css');
const raw = fs.readFileSync(path.join(cssDir, 'storefront-home.bundle.css'), 'utf8')
  .replaceAll('../fonts/', '/fonts/');
if (/@import\b|<\/style/i.test(raw)) throw new Error('Inline home CSS must be self-contained');

// Ultra first-viewport keep-list: chrome + hero + stories + features.
// Everything else (and @keyframes) ships in the deferred remainder so the
// FCP→TTI window under GTmetrix CPU throttle does less Style/Layout work.
const keep = /@(?:font-face)\b|:root\b|(?:^|[^\w-])(?:html\b|body\b|\.ms-page|\.ms-body|\.ms-wrap|\.ms-top|\.ms-logo|\.ms-icon|\.ms-burger|\.ms-promo|\.ms-search|\.ms-hero|\.ms-stories|\.ms-story|\.ms-features|\.ms-feat-|\.ms-drawer|\.ms-fab|\.ms-bottom|\.ms-nav|\.js\b|\.ms-home\b|\.ms-motion|\.ms-reveal\b|\.ms-scroll|\.ms-safe)/;
const isContainScaffold = (body) => /content-visibility|contain-intrinsic-size/.test(body);

const firstSrc = mapStyleRules(
  raw,
  (header, body, original) => {
    if (isContainScaffold(body)) return `${original}{${body}}`;
    if (/^@font-face\b/i.test(header)) return `${original}{${body}}`;
    if (/^@keyframes\b/i.test(header)) return '';
    const selectors = header.split(',').map((s) => s.trim()).filter(Boolean);
    if (selectors.some((sel) => keep.test(sel))) return `${original}{${body}}`;
    return '';
  },
  () => '',
);

const first = transformSync(firstSrc, { loader: 'css', minify: true });
const full = transformSync(raw, { loader: 'css', minify: true });
if (first.warnings.length || full.warnings.length) {
  throw new Error([...first.warnings, ...full.warnings].map((w) => w.text).join('\n'));
}

const firstBanner = '/* Generated by npm run build:critical-home; ultra first-viewport. */\n';
const remBanner = '/* Deferred complete home styles after TBT window. */\n';
const fullBanner = '/* Snapshot of complete home styles. */\n';
fs.writeFileSync(path.join(cssDir, 'critical-home.css'), `${firstBanner}${first.code}`);
fs.writeFileSync(path.join(cssDir, 'critical-home-first.css'), `${firstBanner}${first.code}`);
fs.writeFileSync(path.join(cssDir, 'storefront-home-remainder.css'), `${remBanner}${full.code}`);
fs.writeFileSync(path.join(cssDir, 'critical-home-complete.css'), `${fullBanner}${full.code}`);
console.log(JSON.stringify({
  inlineFirstBytes: Buffer.byteLength(first.code),
  remainderBytes: Buffer.byteLength(full.code),
  completeBytes: Buffer.byteLength(full.code),
}, null, 2));
