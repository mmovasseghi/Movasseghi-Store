import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { transformSync } from 'esbuild';
import { mapStyleRules } from './home-css-rules.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const cssDir = path.join(root, 'src/MovasseghiShop.Web/wwwroot/css');
const raw = fs.readFileSync(path.join(cssDir, 'storefront-home.bundle.css'), 'utf8')
  .replaceAll('../fonts/', '/fonts/');
if (/@import\b|<\/style/i.test(raw)) throw new Error('Inline home CSS must be self-contained');

// Tight first-viewport keep-list: chrome + hero + stories + feature grid.
// Prefixes use (?:-|\\b) so .ms-page / .ms-icon alone do not pull every rule.
// Broad tokens (.js, .ms-motion, .ms-reveal, .ms-scroll, .ms-drawer, .ms-nav,
// bare .ms-page) previously kept ~100KB+ of Style/Layout work in the TBT window
// (yaFJoKbZ ~311ms). Below-fold rules + @keyframes ship in the true remainder
// complement (not a second copy of the full sheet — re-applying full caused CLS).
// Include all .ms-promo-* (not only -bar): missing CTA/line/slogan media rules
// caused desktop CLS ~1.0 when a full duplicate sheet applied.
// OvtAqFtf / Seattle: smaller inline sheet → smaller HTML on high-RTT paths.
// Features/featured/fab stay in the late remainder (below-fold + CV scaffolding).
const keep = /:root\b|(?:^|[^\w-])(?:html\b|body\b|\.ms-skip-link\b|\.ms-app\b|\.ms-main\b|\.ms-page-home\b|\.ms-body\b|\.ms-wrap\b|\.ms-top(?:-|\b)|\.ms-logo\b|\.ms-icon-btn\b|\.ms-burger\b|\.ms-promo(?:-|\b)|\.ms-search(?:-|\b)|\.ms-hero(?:-|\b)|\.ms-stories\b|\.ms-story(?:-|\b)|\.ms-safe\b)/;
const isContainScaffold = (body) => /content-visibility|contain-intrinsic-size/.test(body);
// Global resets (* / img / a) must stay inlined — deferring them with the
// complement made .ms-skip-link sit in normal flow (~25px) until remainder
 // applied, producing desktop CLS ~0.13 (app top 25→0).
const isGlobalReset = (header) => header.split(',').every((s) => {
  const sel = s.trim();
  return /^(?:\*|img|a)(?:[:\[]|$)/.test(sel);
});
const keepRule = (header, body) => {
  if (isContainScaffold(body)) return true;
  if (/^@keyframes\b/i.test(header)) return false;
  if (isGlobalReset(header)) return true;
  const selectors = header.split(',').map((s) => s.trim()).filter(Boolean);
  return selectors.some((sel) => keep.test(sel));
};

// F1St9hRu (Seattle): TBT fixed but LCP 2.3s — @font-face in critical started an
// 86KB woff2 download that competed with the hero image on high-RTT paths.
// Keep fonts (+ keyframes) in the post-LCP remainder only; first paint uses system stack.
const firstSrc = mapStyleRules(
  raw,
  (header, body, original) => (keepRule(header, body) ? `${original}{${body}}` : ''),
  () => '',
);

// True complement: skip anything already inlined; ship fonts + keyframes here.
const remSrc = mapStyleRules(
  raw,
  (header, body, original) => (keepRule(header, body) ? '' : `${original}{${body}}`),
  (header, body, original) => {
    if (/^@font-face\b/i.test(header)) return `${original}{${body}}`;
    if (/^@keyframes\b/i.test(header)) return `${original}{${body}}`;
    return '';
  },
);

const first = transformSync(firstSrc, { loader: 'css', minify: true });
const rem = transformSync(remSrc, { loader: 'css', minify: true });
const full = transformSync(raw, { loader: 'css', minify: true });
if (first.warnings.length || rem.warnings.length || full.warnings.length) {
  throw new Error([...first.warnings, ...rem.warnings, ...full.warnings].map((w) => w.text).join('\n'));
}

const firstBanner = '/* Generated by npm run build:critical-home; tight first-viewport. */\n';
const remBanner = '/* Below-fold complement only (not a full-sheet duplicate). */\n';
const fullBanner = '/* Snapshot of complete home styles. */\n';
fs.writeFileSync(path.join(cssDir, 'critical-home.css'), `${firstBanner}${first.code}`);
fs.writeFileSync(path.join(cssDir, 'critical-home-first.css'), `${firstBanner}${first.code}`);
fs.writeFileSync(path.join(cssDir, 'storefront-home-remainder.css'), `${remBanner}${rem.code}`);
fs.writeFileSync(path.join(cssDir, 'critical-home-complete.css'), `${fullBanner}${full.code}`);
console.log(JSON.stringify({
  inlineFirstBytes: Buffer.byteLength(first.code),
  remainderBytes: Buffer.byteLength(rem.code),
  completeBytes: Buffer.byteLength(full.code),
}, null, 2));
