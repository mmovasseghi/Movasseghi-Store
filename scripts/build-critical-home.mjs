import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { transformSync } from 'esbuild';
import { mapStyleRules } from './home-css-rules.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const cssDir = path.join(root, 'src/MovasseghiShop.Web/wwwroot/css');
// Complete route-specific main styles remain inline before main markup.
// Header rules are repeated in their original cascade to preserve every state.
// Cart-only styles still load on intent; other pages use the cached full bundle.
const bundle = fs.readFileSync(path.join(cssDir, 'storefront-home.bundle.css'), 'utf8')
  .replaceAll('../fonts/', '/fonts/');
if (/@import\b|<\/style/i.test(bundle)) throw new Error('Inline home CSS must be self-contained');
const { code, warnings } = transformSync(bundle, { loader: 'css', minify: true });
if (warnings.length) throw new Error(warnings.map(w => w.text).join('\n'));
fs.writeFileSync(path.join(cssDir, 'critical-home.css'), `/* Generated by npm run build:critical-home; complete home styles. */\n${code}`);
console.log(`Inline home CSS: ${Buffer.byteLength(code)} bytes`);

// Paint the header without waiting for main-page CSS bytes. Main keeps the full
// original cascade, inline before its markup; no async style or timer is needed.
const layout = fs.readFileSync(path.join(root, 'src/MovasseghiShop.Web/Views/Shared/_Layout.cshtml'), 'utf8');
const boundary = layout.indexOf('</header>');
if (boundary < 0) throw new Error('Header boundary missing');
const tokens = new Set();
const sources = [layout.slice(0, boundary)];
const visited = new Set();
while (sources.length) {
  const text = sources.pop();
  for (const token of text.match(/[A-Za-z_][\w-]*/g) || []) tokens.add(token);
  for (const m of text.matchAll(/(?:name\s*=\s*"|PartialAsync\(")(_[A-Za-z0-9]+)/g)) {
    if (visited.has(m[1])) continue;
    visited.add(m[1]);
    const file = path.join(root, 'src/MovasseghiShop.Web/Views/Shared', m[1] + '.cshtml');
    if (fs.existsSync(file)) sources.push(fs.readFileSync(file, 'utf8'));
  }
}
const animations = new Set();
const shell = mapStyleRules(bundle, (header, body, original) => {
  const keep = /\.ms-(?:promo|nav|top|logo|icon-btn|cart-badge|search)(?:-|\b)/.test(header)
    || header.split(',').some(selector => [...selector.matchAll(/[.#]([A-Za-z_][\w-]*)/g)].every(m => tokens.has(m[1])));
  if (!keep) return '';
  for (const word of body.match(/[A-Za-z_][\w-]*/g) || []) animations.add(word);
  return original + '{' + body + '}';
});
const filtered = mapStyleRules(shell, (h, b, original) => original + '{' + b + '}', (h, b, original) => {
  const name = h.match(/^@(?:-webkit-)?keyframes\s+([\w-]+)/);
  return name && !animations.has(name[1]) ? '' : original + '{' + b + '}';
});
// LH desktop uses classic scrollbars. Reserve their space from the first paint
// so RTL content does not shift horizontally when main content starts overflowing.
const header = transformSync(filtered + 'html.ms-home{overflow-y:scroll}@media print{html.ms-home{overflow-y:visible}}', { loader: 'css', minify: true });
if (header.warnings.length) throw new Error(header.warnings.map(w => w.text).join('\n'));
fs.writeFileSync(path.join(cssDir, 'critical-shell.css'), `/* Generated by npm run build:critical-home; initial header styles. */\n${header.code}`);
console.log(`Inline header CSS: ${Buffer.byteLength(header.code)} bytes`);
